-- ─── liquidity_pools (pool-engine) ──────────────────────────────────────────

CREATE TABLE IF NOT EXISTS liquidity_pools (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    token_x_id UUID NOT NULL,
    token_y_id UUID NOT NULL,
    bin_step INT NOT NULL,
    base_fee_bps INT NOT NULL,
    max_variable_fee_bps INT NOT NULL DEFAULT 300,
    volatility_accumulator INT NOT NULL DEFAULT 0,
    decay_period_seconds INT NOT NULL DEFAULT 600,
    active_bin_id INT NOT NULL,
    base_price DECIMAL(30,18) NOT NULL,
    -- Sprint 9-DS-r4 (P1-15) — DEFAULT lowered from 20 → 0 to match
    -- the 3.A legal memo cap of 5% (>5% triggers broker-dealer
    -- re-registration). Pools opt-in to a non-zero value either via
    -- the seed UPDATE in liquidity_pools below, the create-pool API,
    -- or the admin /api/v1/pools/{id}/protocol-fee endpoint.
    protocol_fee_pct INT NOT NULL DEFAULT 0,
    total_tvl_x BIGINT NOT NULL DEFAULT 0,
    total_tvl_y BIGINT NOT NULL DEFAULT 0,
    volume_24h BIGINT NOT NULL DEFAULT 0,
    total_fees_collected_x BIGINT NOT NULL DEFAULT 0,
    total_fees_collected_y BIGINT NOT NULL DEFAULT 0,
    -- Sprint 6 #3.2 / pool-engine Liquibase 009 — protocol-side fee
    -- accumulator, separate from total_fees_collected (which is gross).
    -- Treasury sweep job (Sprint 7+) drains these.
    total_protocol_fee_x BIGINT NOT NULL DEFAULT 0,
    total_protocol_fee_y BIGINT NOT NULL DEFAULT 0,
    -- Sprint 4 #4.2 / pool-engine Liquibase 007 — per-pool
    -- counterparty caps. NULL = uncapped on that side.
    max_single_swap_nominal_x BIGINT,
    max_single_swap_nominal_y BIGINT,
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    created_by UUID NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- Sprint 4 #4.7 / pool-engine Liquibase 006 — JPA @Version optimistic
    -- lock. Without this column the entity @Version fails ddl-auto:validate
    -- on a fresh init-db.sql deploy, AND 04-spasibo-seed.sql's INSERT
    -- references the column.
    version BIGINT NOT NULL DEFAULT 0,
    UNIQUE (token_x_id, token_y_id, bin_step)
);

CREATE INDEX IF NOT EXISTS idx_liquidity_pools_token_x_id ON liquidity_pools (token_x_id);
CREATE INDEX IF NOT EXISTS idx_liquidity_pools_token_y_id ON liquidity_pools (token_y_id);
CREATE INDEX IF NOT EXISTS idx_liquidity_pools_status ON liquidity_pools (status);
CREATE INDEX IF NOT EXISTS idx_liquidity_pools_created_by ON liquidity_pools (created_by);

