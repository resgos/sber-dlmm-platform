-- ─── outbox_events (token-service, optionally other services) ───────────────
-- Transactional outbox: domain-mutation @Transactional writes a row here
-- alongside the balance change; a scheduled dispatcher polls
-- WHERE published_at IS NULL ORDER BY created_at, sends to Kafka, marks
-- published_at. Eliminates the lost-event window between DB commit and
-- Kafka send.
CREATE TABLE IF NOT EXISTS outbox_events (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    aggregate_type VARCHAR(64) NOT NULL,
    -- 128 chars accommodates composite keys like "userId:tokenId"
    -- (two UUIDs = 73 chars + slack).
    aggregate_id VARCHAR(128) NOT NULL,
    event_type VARCHAR(128) NOT NULL,
    topic VARCHAR(128) NOT NULL,
    payload TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at TIMESTAMP,
    attempts INT NOT NULL DEFAULT 0,
    last_error TEXT,
    -- Originator service name. Multiple services share this table;
    -- each dispatcher only polls rows it created (filter on service).
    service VARCHAR(32) NOT NULL DEFAULT 'unknown'
);

-- Partial index scoped per service. Polls become
-- WHERE service = :me AND published_at IS NULL ORDER BY created_at,
-- bounded by the unpublished-per-service queue depth.
CREATE INDEX IF NOT EXISTS idx_outbox_unpublished_per_service
  ON outbox_events (service, created_at)
  WHERE published_at IS NULL;

